    if (path.isEmpty) return 'Unknown file';
    final parts = path.split('/');
    return parts.isNotEmpty ? parts.last : 'Unknown file';
  }

  IconData _getFileIcon(String path) {
    final lowerPath = path.toLowerCase();
    if (lowerPath.endsWith('.pdf')) return Icons.picture_as_pdf;
    if (lowerPath.endsWith('.doc') || lowerPath.endsWith('.docx')) return Icons.description;
    if (lowerPath.endsWith('.xls') || lowerPath.endsWith('.xlsx')) return Icons.table_chart;
    if (lowerPath.endsWith('.txt')) return Icons.text_snippet;
    return Icons.insert_drive_file;
  }

  Future<void> _openFile(BuildContext context) async {
    try {
      final uri = Uri.parse(fileUrl);
      if (await canLaunchUrl(uri)) {
        await launchUrl(uri, mode: LaunchMode.externalApplication);
      } else {
        if (context.mounted) {
          ScaffoldMessenger.of(context).showSnackBar(
            const SnackBar(
              content: Text('Cannot open this file'),
              backgroundColor: Colors.orange,
            ),
          );
        }
      }
    } catch (e) {
      if (context.mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Error opening file: $e'),
            backgroundColor: Colors.red,
          ),
        );
      }
    }
  }

