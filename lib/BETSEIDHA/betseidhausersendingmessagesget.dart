class Autogenerated {
  int? nMemberNotificationsID;
  String? cUploadedPathText;
  int? nMemberID;
  String? cMemberName;
  String? dDate;

  Autogenerated({
    this.nMemberNotificationsID,
    this.cUploadedPathText,
    this.nMemberID,
    this.cMemberName,
    this.dDate,
  });

  Autogenerated.fromJson(Map<String, dynamic> json) {
    nMemberNotificationsID = json['nMemberNotificationsID'];
    cUploadedPathText = json['cUploadedPathText'];
    nMemberID = json['nMemberID'];
    cMemberName = json['cMemberName'];
    dDate = json['dDate'];
  }

  Map<String, dynamic> toJson() {
    final Map<String, dynamic> data = <String, dynamic>{};
    data['nMemberNotificationsID'] = nMemberNotificationsID;
    data['cUploadedPathText'] = cUploadedPathText;
    data['nMemberID'] = nMemberID;
    data['cMemberName'] = cMemberName;
    data['dDate'] = dDate;
    return data;
  }

  String get contentType {
    if (cUploadedPathText == null || cUploadedPathText!.isEmpty) {
      return 'empty';
    }

    final path = cUploadedPathText!.toLowerCase();

    // Check for image extensions
    if (path.endsWith('.jpg') ||
        path.endsWith('.jpeg') ||
        path.endsWith('.png') ||
        path.endsWith('.gif') ||
        path.endsWith('.bmp') ||
        path.endsWith('.webp')) {
      return 'image';
    }

    // Check for video extensions
    if (path.endsWith('.mp4') ||
        path.endsWith('.avi') ||
        path.endsWith('.mov') ||
        path.endsWith('.mkv') ||
        path.endsWith('.webm')) {
      return 'video';
    }

    // Check for voice/audio extensions
    if (path.endsWith('.m4a') ||
        path.endsWith('.mp3') ||
        path.endsWith('.wav') ||
        path.endsWith('.ogg') ||
        path.endsWith('.aac')) {
      return 'voice';
    }

    // Check for file/document extensions
    if (path.endsWith('.pdf') ||
        path.endsWith('.doc') ||
        path.endsWith('.docx') ||
        path.endsWith('.xls') ||
        path.endsWith('.xlsx') ||
        path.endsWith('.txt')) {
      return 'file';
    }

    // Check if it's a URL (starts with http)
    if (path.startsWith('http://') || path.startsWith('https://')) {
      return 'file';
    }

    // Otherwise, treat as text
    return 'text';
  }
}

