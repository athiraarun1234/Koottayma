    final prefs = await SharedPreferences.getInstance();
    final savedToken = prefs.getString('jwt');

    if (savedToken == null || savedToken.isEmpty) {
      throw Exception("Token not found. Please login again.");
    }

    final url = Uri.parse(
        "https://lv4hfxvb-7000.inc1.devtunnels.ms/notifications/approvingmembernotifications/$nMemberNotificationsID/");
    
    final response = await http.put(
      url,
      headers: {
        "Content-Type": "application/json",
        "Authorization": savedToken,
      },
      body: json.encode({}),
    );

    print("Approval - Response Code: ${response.statusCode}");
    print("Approval - Response Body: ${response.body}");

    if (response.statusCode != 201 && response.statusCode != 200) {
      throw Exception("Failed to approve request");
